/// Characters drawn with another's glyph: curly quotes look like straight ones at this size.
pub(super) const ALIASES: &[(char, char)] = &[('‘', '\''), ('’', '\''), ('“', '"'), ('”', '"')];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_rectangles_of_ink_and_blanks() {
        for &(c, rows) in GLYPHS {
            let rows: Vec<&str> = rows.split(' ').collect();
            let width = rows[0].len();
            assert!(width > 0, "{c:?} is empty");
            assert!(rows.len() <= 9, "{c:?} reaches into the next line");
            for row in &rows {
                assert_eq!(row.len(), width, "{c:?} has rows of different widths");
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "{c:?}: {row}");
            }
            assert!(rows.iter().any(|row| row.contains('#')), "{c:?} has no ink");
        }
    }

    #[test]
    fn printable_ascii_is_covered_once() {
        let mut chars: Vec<char> = GLYPHS.iter().map(|&(c, _)| c).collect();
        let count = chars.len();
        chars.sort_unstable();
        chars.dedup();
        assert_eq!(chars.len(), count, "a character is defined twice");
        for c in '!'..='~' {
            assert!(chars.contains(&c), "{c:?} is missing");
        }
        for &(alias, original) in ALIASES {
            assert!(
                chars.contains(&original),
                "{alias:?} aliases a missing glyph"
            );
        }
    }
}
